import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { createServer } from 'vite'

const root = fileURLToPath(new URL('../', import.meta.url))
const seedPath = new URL('../../supabase/artworks.sql', import.meta.url)
const server = await createServer({ root, server: { middlewareMode: true, hmr: false, watch: null }, appType: 'custom' })
try {
  const { collections } = await server.ssrLoadModule('/src/data/artworks.js')
  const quote = value => `'${value.replaceAll("'", "''")}'`
  const records = collections.flatMap(collection => collection.artworks)
  const values = records.map(artwork => `  (${quote(artwork.id)}, ${quote(artwork.title)}, 1000)`).join(',\n')
  const seed = `-- Generated by npm run sync:auction in fontend.\n-- Apply this file to update artwork listings without replaying migrations.\nbegin;\ninsert into auction_private.artworks(id, title, starting_price_cents) values\n${values}\non conflict (id) do update set title = excluded.title;\ncommit;\n`
  if (process.argv.includes('--check')) {
    const source = await readFile(seedPath, 'utf8')
    if (source !== seed) throw new Error('Auction artworks are out of sync. Run npm run sync:auction in fontend.')
  } else {
    await writeFile(seedPath, seed)
  }
} finally { await server.close() }
